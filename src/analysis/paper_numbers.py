"""Write reports/paper_numbers.tex: one \\newcommand per number the paper cites.

Generated by run_all.py from the result tables; never edit the .tex by hand. In the
paper: \\input{paper_numbers} in the preamble, then e.g. "N = \\NDaosFinal{} DAOs".
Macro names contain letters only (LaTeX rule): digits are spelled out.
"""
import re

import numpy as np
import pandas as pd

import config

DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five",
          "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def _name(s):
    s = "".join(DIGITS.get(ch, ch) for ch in s)
    return re.sub(r"[^A-Za-z]", "", s)


class Macros:
    def __init__(self):
        self.lines = []

    def add(self, name, value, fmt="{:.2f}", comment=""):
        if value is None or (isinstance(value, float) and np.isnan(value)):
            txt = "n/a"
        elif isinstance(value, (int, np.integer)):
            txt = f"{int(value):,}".replace(",", "{,}")
        elif isinstance(value, str):
            txt = value
        else:
            txt = fmt.format(value)
        self.lines.append(f"\\newcommand{{\\{_name(name)}}}{{{txt}}}" + (f"  % {comment}" if comment else ""))


def run():
    T, P = config.TABLES, config.DATA_PROCESSED
    m = Macros()
    cs = pd.read_csv(P / "cross_section.csv")

    # sample funnel
    f = pd.read_csv(T / "sample_funnel_summary.csv")
    for step, n in zip(f.step, f.n):
        m.add("NFunnel" + step.split()[0], int(n), comment=step)
    m.add("NDaosFinal", len(cs))
    m.add("NDaosSupplyCheck", int((cs.match_basis == "supply check passed").sum()))
    m.add("NDaosAuthorAccepted", int(cs.match_basis.str.startswith("accepted").sum()))
    m.add("NDaosPrices", int(cs.n_months.notna().sum()))
    m.add("NDaosActive", int(cs.active_12m.sum()))
    m.add("NDaosMcapValid", int(cs.mcap_usd.notna().sum()))
    m.add("NDaosFdvLive", int(cs.fdv_live.notna().sum()))
    m.add("NDaosFdvAvg", int(cs.fdv_avg.notna().sum()))
    m.add("NDaosDormant", int((cs.dormancy_ratio > 1).sum()), comment="max past votes cast > current delegated votes")
    m.add("NGovernorChanges", len(pd.read_csv(config.REPORTS / "governor_selection_changes.csv")))
    for st, n in cs.q_status.fillna("no governance data").value_counts().items():
        m.add("NQStatus" + st.split("(")[0].title(), int(n), comment=st)

    # descriptives
    d = pd.read_csv(T / "new_descriptives.csv")
    for v in d.dropna(subset=["mean"]).itertuples():
        base = _name(v.variable.replace("top-100", "top hundred").title())
        m.add(base + "N", int(v.n))
        m.add(base + "Mean", v.mean, "{:.3g}")
        m.add(base + "Median", v.median, "{:.3g}")

    # quorum capture
    q = pd.read_csv(T / "new_quorum_capture.csv")
    for r in q.itertuples():
        s = r.sample.title()
        m.add(f"QCapture{s}N", int(r.n_q_reached))
        m.add(f"QCapture{s}One", int(r.n_q_equal_1))
        m.add(f"QCapture{s}SharePct", 100 * r.share_q_equal_1, "{:.0f}")
        m.add(f"QCapture{s}MedQuorumPct", 100 * r.median_quorum_share_of_delegated, "{:.0f}")
        m.add(f"QCapture{s}MedTopOnePct", 100 * r.median_top1_share, "{:.0f}")

    # H1
    sp = pd.read_csv(T / "new_h1_spearman.csv")
    size_key = {"FDV, live tokens (main)": "Live", "CryptoCompare market cap": "Mcap",
                "FDV, average over trading life": "Life"}
    for r in sp.itertuples():
        k = f"HOne{r.sample.title()}{size_key[r.size]}{_name(r.variable.title())}"
        m.add(k + "N", int(r.n))
        m.add(k + "Rho", r.rho)
        m.add(k + "P", r.p, "{:.3f}")
        m.add(k + "CILow", r.ci_low)
        m.add(k + "CIHigh", r.ci_high)
        m.add(k + "MDE", r.min_detectable_rho_80pct)
    ols1 = pd.read_csv(T / "new_h1_ols.csv")
    for r in ols1[ols1.term.isin(["ln_hhi", "ln_delegates"])].itertuples():
        k = f"HOneOls{r.sample.title()}{size_key[r.size]}{_name(r.model.split()[0])}{_name(r.term.title())}"
        m.add(k + "Coef", r.coef)
        m.add(k + "SE", r.se)
        m.add(k + "P", r.p, "{:.3f}")
        m.add(k + "N", int(r.n))
    bt = pd.read_csv(T / "new_h1_bootstrap.csv")
    for r in bt.itertuples():
        k = f"HOneBoot{r.sample.title()}"
        m.add(k + "Mean", r.mean)
        m.add(k + "SharePct", 100 * r.share_negative, "{:.1f}")
        m.add(k + "P", r.p_two_sided, "{:.3f}")

    # H2
    h2 = pd.read_csv(T / "new_h2_ols.csv")
    h2 = h2[(h2.dep == "avg_log_return") & (h2.term == "ln_hhi")]
    for r in h2.itertuples():
        k = f"HTwo{_name(r.model)}"
        m.add(k + "HhiCoef", r.coef, "{:.3f}")
        m.add(k + "HhiP", r.p, "{:.3f}")
        m.add(k + "N", int(r.n))

    # H3
    h3 = pd.read_csv(T / "new_h3_summary.csv").set_index("item").value
    m.add("NEventDaos", int(float(h3["DAOs"])))
    m.add("NEventProposals", int(float(h3["proposals (events)"])))
    m.add("NEventDates", int(float(h3["unique event dates"])))
    m.add("CARPct", 100 * float(h3["CAR[-5,+5] (proposal-weighted)"]))
    m.add("CARDaoEqualPct", 100 * float(h3["CAR[-5,+5] (DAO-equal)"]))
    rb = pd.read_csv(T / "new_h3_robust.csv")
    key = {"proposals": "Props", "event dates": "Dates", "non-overlapping event dates": "NonOverlap"}
    for r in rb[rb.measure == "excess_car"].itertuples():
        k = f"HThree{key[r.sample]}"
        m.add(k + "N", int(r.n_events))
        m.add(k + "ExcessPct", 100 * r.mean)
        m.add(k + "PDao", r.p_cluster_dao, "{:.3f}")
        m.add(k + "PDaoMonth", r.p_cluster_dao_month, "{:.3f}")
        m.add(k + "PDaoLevel", r.dao_level_p, "{:.3f}")
    for r in rb[rb.measure.str.startswith("placebo")].itertuples():
        k = f"HThree{key[r.sample]}Placebo{'Event' if 'event' in r.measure else 'Dao'}"
        m.add(k + "MeanPct", 100 * r.placebo_mean)
        m.add(k + "P", r.placebo_p_one_sided, "{:.3f}")

    # H4
    h4 = pd.read_csv(T / "new_h4_panel.csv")
    b0 = h4[(h4.model.str.startswith("M0")) & (h4.term == "btc_return")].iloc[0]
    m.add("HFourBeta", b0.coef)
    m.add("HFourBetaSE", b0.se)
    m.add("HFourRTwo", b0.r2)
    m.add("HFourNDaos", int(b0.n_daos))
    m.add("HFourNObs", int(b0.n))
    for spec in ["scale-free", "thesis-like"]:
        s = h4[h4.spec == spec]
        k = "HFour" + _name(spec.title())
        for mod in ["M1", "M2", "M3"]:
            r2 = s[s.model.str.startswith(mod)].r2.iloc[0]
            m.add(k + _name(mod) + "RTwo", r2, "{:.3f}")
        m.add(k + "NDaos", int(s.n_daos.iloc[0]))
        m.add(k + "NObs", int(s.n.iloc[0]))
        hh = s[(s.model.str.startswith("M3")) & (s.term == "ln_hhi")].iloc[0]
        m.add(k + "MThreeHhiPWild", hh.p_wild_cluster, "{:.3f}")

    header = ["% Generated by run_all.py (src/analysis/paper_numbers.py). Do not edit by hand.",
              f"% Collection date {config.COLLECTION_DATE}; sample {config.SAMPLE_START} to {config.SAMPLE_END_COLLECT}."]
    names = [ln.split("}")[0] for ln in m.lines]
    dup = sorted({n for n in names if names.count(n) > 1})
    assert not dup, f"duplicate macro names: {dup}"
    (config.REPORTS / "paper_numbers.tex").write_text("\n".join(header + m.lines) + "\n")
    return len(m.lines)
